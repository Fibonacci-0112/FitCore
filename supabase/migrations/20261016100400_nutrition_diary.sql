-- Nutrition: private prices, the food diary and diary days (BRD §6.1; implementation plan §4; R1 PR 3).
--
-- Rules the tables keep (BRD §6.1):
--   * Money is integer minor units plus an ISO 4217 code.
--   * A diary entry keeps the nutrients and estimated cost it had at log time, so editing a food or a price never
--     rewrites history (NFR-REL-4). The food, serving and price ids are only references back.
--   * diary_date is the member's local calendar date.
--   * A day without a diary_days row is unknown, never zero intake. Only complete days feed adaptive targets.
--
-- Unit and status codes match FitCore.Domain: QuantityUnit and CostStatus, abbreviated and in snake case.
--
-- Access (BRD §3.2 "Food diary & estimated cost"): the member reads and writes; a coach or clinician with an active
-- `nutrition` grant reads entries and days. Prices stay private to the member: grantees see each entry's estimated
-- cost, not the member's price list.

-- A member's price for a food: what one package of a given size cost from a given local date.
create table nutrition.food_prices (
  id uuid primary key default gen_random_uuid(),
  member_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  food_id uuid not null references catalog.foods (id) on delete cascade,
  package_amount numeric(12, 3) not null check (package_amount > 0),
  package_unit text not null check (package_unit in (
    'g', 'ml', 'serving', 'mg', 'kg', 'oz', 'lb', 'l', 'tsp', 'tbsp', 'fl_oz', 'cup', 'pint', 'quart', 'gallon')),
  package_serving_id uuid,
  price_minor bigint not null check (price_minor >= 0),
  currency char(3) not null check (currency ~ '^[A-Z]{3}$'),
  effective_date date not null,
  -- Breaks ties between prices with the same effective date: the newest wins (implementation plan §4).
  created_at timestamptz not null default now(),
  check ((package_unit = 'serving') = (package_serving_id is not null)),
  foreign key (package_serving_id, food_id) references catalog.food_servings (id, food_id) on delete cascade,
  -- Lets diary entries require that a price is for the food they name.
  unique (id, food_id)
);

create index food_prices_lookup on nutrition.food_prices (member_id, food_id, currency, effective_date desc, created_at desc);

-- One food eaten. The id is generated by the client, so a retried save inserts nothing new (implementation plan §3.2).
create table nutrition.diary_entries (
  id uuid primary key,
  member_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  diary_date date not null,
  meal text not null check (meal in ('breakfast', 'lunch', 'dinner', 'snack')),
  -- References back. Deleting the food, serving or price clears them; the snapshot below stays.
  food_id uuid references catalog.foods (id) on delete set null,
  serving_id uuid,
  price_id uuid references nutrition.food_prices (id) on delete set null,
  -- The amount as the member entered it.
  amount numeric(12, 3) not null check (amount > 0),
  unit text not null check (unit in (
    'g', 'ml', 'serving', 'mg', 'kg', 'oz', 'lb', 'l', 'tsp', 'tbsp', 'fl_oz', 'cup', 'pint', 'quart', 'gallon')),
  -- Snapshot at log time: the food as it was, the amount in canonical units where known, and the nutrients eaten.
  food_name text not null check (char_length(food_name) between 1 and 200),
  food_brand text check (char_length(food_brand) between 1 and 200),
  serving_label text check (char_length(serving_label) between 1 and 80),
  grams numeric(12, 3) check (grams > 0),
  ml numeric(12, 3) check (ml > 0),
  serving_count numeric(12, 3) check (serving_count > 0),
  energy_kcal numeric(9, 2) check (energy_kcal >= 0),
  protein_g numeric(9, 2) check (protein_g >= 0),
  carbs_g numeric(9, 2) check (carbs_g >= 0),
  fat_g numeric(9, 2) check (fat_g >= 0),
  fiber_g numeric(9, 2) check (fiber_g >= 0),
  sugar_g numeric(9, 2) check (sugar_g >= 0),
  saturated_fat_g numeric(9, 2) check (saturated_fat_g >= 0),
  sodium_mg numeric(10, 2) check (sodium_mg >= 0),
  -- Estimated food cost, never "spend" (BRD §6.1).
  cost_status text not null check (cost_status in (
    'priced', 'no_price', 'not_yet_effective', 'currency_mismatch', 'unconvertible')),
  cost_minor bigint check (cost_minor >= 0),
  currency char(3) check (currency ~ '^[A-Z]{3}$'),
  -- Bumped on every update, so sync can detect a conflicting edit (architecture-options §B.4).
  version integer not null default 1 check (version > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((cost_status = 'priced') = (cost_minor is not null)),
  check ((cost_minor is null) = (currency is null)),
  -- Deleting the price clears price_id; the entry stays priced.
  check (price_id is null or cost_status = 'priced'),
  check (unit <> 'serving' or serving_count is not null),
  -- The serving belongs to the entry's food. The second key clears serving_id when the food goes first, which
  -- leaves food_id null and takes the first key out of play.
  foreign key (serving_id, food_id) references catalog.food_servings (id, food_id) on delete set null (serving_id),
  foreign key (serving_id) references catalog.food_servings (id) on delete set null,
  -- The price is for the entry's food, so an entry's cost never comes from another food's price.
  foreign key (price_id, food_id) references nutrition.food_prices (id, food_id) on delete set null (price_id)
);

create index diary_entries_day on nutrition.diary_entries (member_id, diary_date);

-- The member's "this day is complete" mark.
create table nutrition.diary_days (
  member_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  diary_date date not null,
  is_complete boolean not null,
  updated_at timestamptz not null default now(),
  primary key (member_id, diary_date)
);

alter table nutrition.food_prices enable row level security;
alter table nutrition.diary_entries enable row level security;
alter table nutrition.diary_days enable row level security;

-- Prices: the member's own, for foods the member can see. The subquery runs under the caller's policies on foods.
create policy food_prices_select_own on nutrition.food_prices for select to authenticated
  using (member_id = (select auth.uid()));
create policy food_prices_insert_own on nutrition.food_prices for insert to authenticated
  with check (member_id = (select auth.uid()) and exists (select 1 from catalog.foods f where f.id = food_id));
create policy food_prices_update_own on nutrition.food_prices for update to authenticated
  using (member_id = (select auth.uid()))
  with check (member_id = (select auth.uid()) and exists (select 1 from catalog.foods f where f.id = food_id));
create policy food_prices_delete_own on nutrition.food_prices for delete to authenticated
  using (member_id = (select auth.uid()));

-- Entries: the member writes; a nutrition grantee reads. A new or edited entry may name only a food the member can
-- see, a serving of that food and a price of the member's own for it. A serving or price needs the food beside it:
-- with food_id null the composite keys don't apply, and the plain serving key checks existence without RLS.
create policy diary_entries_select on nutrition.diary_entries for select to authenticated
  using (member_id = (select auth.uid()) or care.has_grant(member_id, 'nutrition'));
create policy diary_entries_insert_own on nutrition.diary_entries for insert to authenticated
  with check (
    member_id = (select auth.uid())
    -- Checked here rather than as a table constraint, so deleting a serving later only clears the reference.
    and (unit <> 'serving' or serving_id is not null)
    and ((serving_id is null and price_id is null) or food_id is not null)
    and (food_id is null or exists (select 1 from catalog.foods f where f.id = food_id))
    and (price_id is null or exists (
      select 1 from nutrition.food_prices p where p.id = price_id and p.member_id = (select auth.uid()))));
-- Deleting a food clears serving_id and price_id along with food_id, so an entry left behind still passes.
create policy diary_entries_update_own on nutrition.diary_entries for update to authenticated
  using (member_id = (select auth.uid()))
  with check (
    member_id = (select auth.uid())
    and ((serving_id is null and price_id is null) or food_id is not null)
    and (food_id is null or exists (select 1 from catalog.foods f where f.id = food_id))
    and (price_id is null or exists (
      select 1 from nutrition.food_prices p where p.id = price_id and p.member_id = (select auth.uid()))));
create policy diary_entries_delete_own on nutrition.diary_entries for delete to authenticated
  using (member_id = (select auth.uid()));

-- Days: the member writes; a nutrition grantee reads.
create policy diary_days_select on nutrition.diary_days for select to authenticated
  using (member_id = (select auth.uid()) or care.has_grant(member_id, 'nutrition'));
create policy diary_days_insert_own on nutrition.diary_days for insert to authenticated
  with check (member_id = (select auth.uid()));
create policy diary_days_update_own on nutrition.diary_days for update to authenticated
  using (member_id = (select auth.uid())) with check (member_id = (select auth.uid()));
create policy diary_days_delete_own on nutrition.diary_days for delete to authenticated
  using (member_id = (select auth.uid()));

grant usage on schema nutrition to authenticated;
grant select, insert, update, delete on nutrition.food_prices, nutrition.diary_entries, nutrition.diary_days
  to authenticated;

create function nutrition.touch() returns trigger
language plpgsql set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end
$$;

create function nutrition.touch_entry() returns trigger
language plpgsql set search_path = ''
as $$
begin
  new.updated_at := now();
  new.version := old.version + 1;
  return new;
end
$$;

revoke all on function nutrition.touch(), nutrition.touch_entry() from public, anon, authenticated, service_role;

create trigger diary_entries_touch before update on nutrition.diary_entries
  for each row execute function nutrition.touch_entry();
create trigger diary_days_touch before update on nutrition.diary_days
  for each row execute function nutrition.touch();
